// RmlUi's font engine, over the GAME'S OWN alphabets - no FreeType anywhere.
//
//
// ⚠️ THIS IS WHY `RMLUI_FONT_ENGINE=none`. RmlUi normally draws text with FreeType; here every
// typeface IS an asset of the game, out of `ALWAYS.WAP`. One less third-party library, and the
// original's own lettering. Three families a stylesheet can ask for:
//
//   bigred  - `SML_ALPH.SPR`, 79 glyphs of 8x8: the plain, steady lettering. Lists, fact
//             sheets, hints, anything read rather than looked at (the original draws its
//             vehicle and driver sheets this way too).
//   wibs    - the WIBBLY lettering of the original's menus: `WIBS1..5.SPR`, five drawings of
//             the same 85-glyph alphabet (29 rows), cycled every 5 ticks = 70 ms. It is what
//             `anim 5,5,7, 2,3,4,5,6` in every `.SCN` does to fonts 2..6.
//   wibs-b  - the same, TWO FRAMES AHEAD: CONFSCN's second line `anim 5,5,7, 4,5,6,2,3`, so
//             neighbouring lines do not wobble in step.
//
// ⚠️ EVERY GLYPH IS PIXEL ART, so the size in the stylesheet is rounded DOWN to a whole
// multiple of the artwork's height (8 or 29 rows, never below 1x). `font-size: 20px` on
// SML_ALPH draws at 16, not at 2.5x with half a pixel of smear. The HUD learned this the hard
// way - see render/hud.h.
//
// ⚠️ THE WOBBLE IS A FONT THAT CHANGES, NOT A DOCUMENT THAT CHANGES. set_clock_ms() moves the
// frame and GetVersion() tells RmlUi the wibbly faces have new glyphs, so every such text is
// regenerated by RmlUi itself - no screen touches its elements to animate them.
#pragma once

#include <RmlUi/Core/FontEngineInterface.h>

#include <cstdint>
#include <string>
#include <vector>

#include "formats/sprite.h"
#include "formats/threedw.h"   // RGB

namespace bigred {

class RmlRenderInterface;

class RmlFontEngine : public Rml::FontEngineInterface {
public:
    // Decodes the game's alphabets and hands one atlas to the renderer, which is what turns it
    // into a texture RmlUi can reference. False when `ALWAYS.WAP` is not there: the menus then
    // draw without text rather than not at all.
    bool load(const std::string& game_dir, RmlRenderInterface& renderer);

    // The family a stylesheet asks for by default: `font-family: bigred;`.
    static const char* family() { return "bigred"; }

    // The wall clock the wibbly lettering runs on (docs: never a frame count - the menus must
    // wobble at one speed at 30 fps and at 240). Called once a frame by every menu.
    static void set_clock_ms(uint32_t ms);

    // --- what RmlUi calls -------------------------------------------------------------------
    bool LoadFontFace(const Rml::String& file_name, int face_index, bool fallback_face,
                      Rml::Style::FontWeight weight) override;
    Rml::FontFaceHandle GetFontFaceHandle(const Rml::String& family, Rml::Style::FontStyle style,
                                          Rml::Style::FontWeight weight, int size) override;
    const Rml::FontMetrics& GetFontMetrics(Rml::FontFaceHandle handle) override;
    int GetStringWidth(Rml::FontFaceHandle handle, Rml::StringView string,
                       const Rml::TextShapingContext& text_shaping_context,
                       Rml::Character prior_character) override;
    int GenerateString(Rml::RenderManager& render_manager, Rml::FontFaceHandle face_handle,
                       Rml::FontEffectsHandle font_effects_handle, Rml::StringView string,
                       Rml::Vector2f position, Rml::ColourbPremultiplied colour, float opacity,
                       const Rml::TextShapingContext& text_shaping_context,
                       Rml::TexturedMeshList& mesh_list) override;
    int GetVersion(Rml::FontFaceHandle handle) override;

private:
    enum class Kind { Plain, Wibs, WibsB };
    // One size of one family. A handle is an index into this, plus one.
    struct Face {
        Kind kind = Kind::Plain;
        int scale = 1;                 // whole-number magnification of the artwork
        Rml::FontMetrics metrics{};
    };
    struct Glyph {
        float u0 = 0, v0 = 0, u1 = 0, v1 = 0;
        int width = 0, height = 0, advance = 0;
        bool ok = false;
    };
    // One `.SPR` alphabet, laid into the shared atlas.
    struct Sheet {
        std::vector<Glyph> glyphs;     // indexed by character - 32
        int rows = 0;                  // the artwork's own height
    };

    Face* face_for(Rml::FontFaceHandle handle);
    // The sheet a face draws from NOW: the plain alphabet, or the wibbly frame the clock is on.
    const Sheet& sheet_for(const Face& f) const;
    // Which glyph a character (a code point of the UTF-8 text) draws, or -1 for none.
    int glyph_of(const Face& f, char32_t c) const;

    std::vector<Sheet> sheets_;        // [0] SML_ALPH, [1..5] WIBS1..5 when they loaded
    std::vector<Face> faces_;
    bool ready_ = false;
};

} // namespace bigred
